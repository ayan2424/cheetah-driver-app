extension AppStringTranslation on String {
  String localize([String? langCode]) {
    String code = langCode ?? 'en';
    if (langCode == null && Get.isRegistered<AuthController>()) {
      code = Get.find<AuthController>().appLanguage.value;
    }
    return AppTranslations.get(this, code);
  }

  String tr([String? langCode]) {
    return localize(langCode);
  }
}
