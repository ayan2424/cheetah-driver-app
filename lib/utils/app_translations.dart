  static String get(String text, String langCode) {
    final langMap = _keys[langCode];
    if (langMap != null && langMap.containsKey(text)) {
      return langMap[text]!;
    }
    if (langCode.contains('-')) {
      final baseLang = langCode.split('-')[0];
      final baseMap = _keys[baseLang];
      if (baseMap != null && baseMap.containsKey(text)) {
        return baseMap[text]!;
      }
    }
    final enMap = _keys['en'];
    if (enMap != null && enMap.containsKey(text)) {
      return enMap[text]!;
    }
    return text;
  }
}

extension AppStringTranslation on String {
  String localize([String? langCode]) {
    String code = langCode ?? 'en';
    if (langCode == null && Get.isRegistered<AuthController>()) {
      code = Get.find<AuthController>().appLanguage.value;
    }
    return AppTranslations.get(this, code);
  }

  String tr([String? langCode]) {
    return localize(langCode);
  }
}
